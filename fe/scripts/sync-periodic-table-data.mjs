/**
 * Maintainer-only synchronisation aid. It is never imported by the app or a
 * build. Downloaded data must be reviewed, reconciled with CIAAW/NIST, and
 * committed as a new static snapshot before it reaches the UI.
 *
 * Usage: node scripts/sync-periodic-table-data.mjs --write
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(here, '..', 'data', 'periodic-table', 'pubchem-periodic-table.csv');
const propertiesOutput = path.join(here, '..', 'components', 'periodic-table', 'snapshot-pubchem-properties.ts');
const endpoint = 'https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/CSV';
const delay = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));

async function fetchPubChem() {
  // A single request plus a conservative pause keeps this tool below the
  // published PUG REST request-rate guidance when extended later.
  const response = await fetch(endpoint, { headers: { Accept: 'text/csv', 'User-Agent': 'EDUA-periodic-table-sync/1.0' } });
  await delay(250);
  if (!response.ok) throw new Error(`PubChem returned HTTP ${response.status}`);
  const csv = await response.text();
  if (!csv.includes('AtomicNumber') && !csv.includes('Atomic Number')) throw new Error('PubChem response is not a periodic-table CSV');
  return csv;
}

function parseCsv(csv) {
  const rows = [];
  let row = [], value = '', quoted = false;
  for (let index = 0; index < csv.length; index += 1) {
    const char = csv[index];
    if (char === '"') {
      if (quoted && csv[index + 1] === '"') { value += char; index += 1; }
      else quoted = !quoted;
    } else if (char === ',' && !quoted) { row.push(value); value = ''; }
    else if ((char === '\n' || char === '\r') && !quoted) {
      if (char === '\r' && csv[index + 1] === '\n') index += 1;
      row.push(value); rows.push(row); row = []; value = '';
    } else value += char;
  }
  if (value || row.length) { row.push(value); rows.push(row); }
  const [headers, ...values] = rows;
  return values.filter((cells) => cells.length === headers.length).map((cells) => Object.fromEntries(headers.map((header, index) => [header, cells[index]])));
}

function numberOrNull(value) { return value === '' || value === undefined ? null : Number(value); }
function celsius(kelvin) { return kelvin === null ? null : Number((kelvin - 273.15).toFixed(6)); }

async function writePropertiesSnapshot(csv) {
  const records = parseCsv(csv).map((row) => {
    const state = { Solid: 'solid', Liquid: 'liquid', Gas: 'gas' }[row.StandardState] ?? 'unknown';
    const affinityEv = numberOrNull(row.ElectronAffinity);
    return {
      atomicNumber: Number(row.AtomicNumber),
      state,
      meltingPoint: celsius(numberOrNull(row.MeltingPoint)),
      boilingPoint: celsius(numberOrNull(row.BoilingPoint)),
      density: numberOrNull(row.Density),
      electronegativity: numberOrNull(row.Electronegativity),
      electronAffinity: affinityEv === null ? null : Number((affinityEv * 96.485).toFixed(6)),
    };
  });
  if (records.length !== 118 || new Set(records.map((record) => record.atomicNumber)).size !== 118) throw new Error('PubChem CSV did not contain 118 unique elements');
  // Construct fields explicitly so the generated source stays stable in review.
  const stableContent = `// Generated by scripts/sync-periodic-table-data.mjs from the committed PubChem CSV.\n// Temperatures are converted K -> °C; electron affinity is converted eV -> kJ/mol.\nimport type { ElementState } from './types';\n\nexport interface PubChemProperties {\n  state: ElementState;\n  meltingPoint: number | null;\n  boilingPoint: number | null;\n  density: number | null;\n  electronegativity: number | null;\n  electronAffinity: number | null;\n}\n\nexport const PUBCHEM_PROPERTIES: Readonly<Record<number, PubChemProperties>> = {\n${records.map(({ atomicNumber, ...record }) => `  ${atomicNumber}: ${JSON.stringify(record)},`).join('\n')}\n};\n`;
  await fs.writeFile(propertiesOutput, stableContent, 'utf8');
}

if (!process.argv.includes('--write')) {
  console.log('Dry run. Re-run with --write to save the PubChem CSV for review.');
  process.exit(0);
}
const csv = await fetchPubChem();
await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, csv, 'utf8');
await writePropertiesSnapshot(csv);
console.log(`Saved PubChem source CSV to ${output}. Reconcile identity/atomic weights with CIAAW 2024 and electron data with NIST ASD before updating the snapshot.`);
